class Solution {
    public int solution(int n) {
        // 2 x N 타일링의 변형 문제
        // 기존에는 규칙을 세워서 바텀업 방식 풀이
        
        // 3 x N 타일링 또한 만들 수 있는 경우부터 규칙을 발견하기
        // 그림을 그려보니
        // 전체 넓이인 3 x N이 짝수여야 해서 홀수 길이는 채울 수 없음
        
        // 그리고 또
        // 3 x 2는 가로 타일 3개를 쌓는 경우 1가지
        // 세로 타일 2개와 가로 타일 2개를 조합하는 경우가 위아래 대칭으로 2가지
        // 따라서 총 3가지가 나옴
        
        // 3 x 4는 앞의 3 x 2를 채우는 3가지 각각에
        // 다시 3 x 2의 기본 모양 3가지를 이어 붙일 수 있어서 3 x 3 = 9가지
        // 여기에 가운데 2칸과 3칸을 걸쳐 연결하는 특수 모양이
        // 위아래 대칭으로 2가지 더 존재해서 총 11가지가 나옴
        
        // 3 x 6은 앞의 3 x 4를 채우는 11가지 각각에
        // 3 x 2의 기본 모양 3가지를 이어 붙이는 경우가 11 x 3 = 33가지
        // 그리고 앞의 3 x 2 뒤에 3 x 4에서 생긴 특수 모양 2가지를 붙이는 경우가 3 x 2 = 6가지
        // 마지막으로 2와 3, 4와 5를 걸쳐 이어지는
        // 3 x 6에서만 새롭게 생기는 특수 모양이 위아래 대칭으로 2가지 존재
        // 따라서 총 33 + 6 + 2 = 41가지가 나옴
        
        // 즉, 이전 경우에 3 x 2 기본 모양 3가지를 붙이는 경우가 반복되고
        // 3 x 4부터는 각 길이에서만 만들 수 있는 특수 모양이 2가지씩 추가됨
        
        // 홀수면 만들어지지가 않음
        if (n % 2 == 1) {
            return 0;
        }
        
        // dp[i] : 3 x i 크기를 채우는 경우의 수
        long[] dp = new long[n + 1];
        
        // 아무것도 채우지 않는 경우
        dp[0] = 1;
        
        // 3 x 2를 채우는 경우는 3가지
        dp[2] = 3;
        
        // 짝수만 가능
        for (int i = 4; i <= n; i += 2) {
            // 이전 경우에 3 x 2 기본 모양 3가지를 붙이는 경우
            dp[i] = dp[i - 2] * 3;
            
            // 이전 길이들에 각 길이의 특수 모양 2가지를 붙이는 경우
            for (int j = i - 4; j >= 0; j -= 2) {
                dp[i] += dp[j] * 2;
            }
            
            dp[i] %= 1000000007;
        }
        
        return (int) dp[n];
    }
}